    pdu_id,
    CASE 
        WHEN prise_id <= 8 THEN 'Block A'
        ELSE 'Block B'
    END as block,
    COUNT(*) as nombre_prises,
    AVG(valeur) as intensite_moyenne
FROM capteurelectrique 
